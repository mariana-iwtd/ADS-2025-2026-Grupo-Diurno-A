package Grupo_Diurno_A;

public class AtributeInfo {
    private String name;
    private String type;

    //construtor
    public AtributeInfo(String name, String type) {
        this.name = name;
        this.type = type;
    }

    //getters
    public String getName() {
        return name;
    }

    public String getType() {
        return type;
    }

}
